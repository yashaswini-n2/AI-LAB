import random

N = 4

def cost(s):
    return sum(s[i] == s[j] or abs(s[i]-s[j]) == j-i
               for i in range(N) for j in range(i+1, N))

def hill_climbing():
    s = list(range(N))
    random.shuffle(s)
    print("Initial state:", s)
    print("Initial cost:", cost(s))

    while True:
        neighbors = []
        for i in range(N):
            for j in range(i+1, N):
                t = s.copy()
                t[i], t[j] = t[j], t[i]
                neighbors.append(t)

        best = min(neighbors, key=cost)
        if cost(best) >= cost(s):
            break
        s = best
        print("Current state:", s)
        print("Current cost:", cost(s))

    print("\nFinal state:", s)
    print("Final cost:", cost(s))
    if cost(s) == 0:
        print("Solution found!")
        for r in range(N):
            print(" ".join("Q" if s[c] == r else "." for c in range(N)))
    else:
        print("Local minimum reached.")

hill_climbing()

import random
import math

N = 8

def cost(s):
    return sum(
        abs(s[i] - s[j]) == j - i
        for i in range(N)
        for j in range(i + 1, N)
    )

def simulated_annealing():
    for attempt in range(100):
        current = list(range(N))
        random.shuffle(current)
        T = 10

        while T > 0.001:
            if cost(current) == 0:
                print("Final state:", current)
                print("Cost:", cost(current))
                print("Solution found!")
                for r in range(N):
                    print(" ".join(
                        "Q" if current[c] == r else "."
                        for c in range(N)
                    ))
                return

            next_state = current.copy()
            i, j = random.sample(range(N), 2)
            next_state[i], next_state[j] = next_state[j], next_state[i]

            delta = cost(current) - cost(next_state)

            if delta > 0 or random.random() < math.exp(delta / T):
                current = next_state

            T *= 0.995

    print("Solution not found. Run again.")

simulated_annealing()

